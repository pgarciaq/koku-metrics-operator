// RBAC coverage for dynamic-client reads (#744).
//
// controller-gen derives config/rbac/role.yaml from the +kubebuilder:rbac
// markers on the controller. Typed-client access routes through the generated
// clientset/clients and is therefore marker-driven, but dynamic clients name
// their GVR in code, and nothing ties those names back to a marker. #739 was
// that gap: the Machines read shipped with no grant, every other check stayed
// green, and the field it fills was silently empty.
//
// These tests read the generated ClusterRole and require a grant for each read
// below. Reading the generated file (not the markers) is deliberate: a dropped
// marker only becomes visible after `make manifests`, which is exactly the
// sequence that deleted the Machines grant the second time.

// rbacRoleFile is the generated file holding both the ClusterRole and the
// namespaced Role. Cluster-scoped reads must appear in the former; a grant that
// lands in the latter is inert, so treating the two as one grant map would be a
// false green.
const rbacRoleFile = "../../config/rbac/role.yaml"

// collectorDynamicRead pins one dynamic-client read to the verbs the code
// actually issues: List everywhere (listClusterResources) except
// clusterversions, which is fetched by name. Verbs are the code's requirement,
// not the full marker set — markers may grant more (hostedclusters and
// hostedcontrolplanes carry watch), and a superset must not fail the test.
type collectorDynamicRead struct {
	group    string
	resource string
	verbs    []string
	sources  []string
}

var collectorDynamicReads = []collectorDynamicRead{
	{machineAPIGroup, machineResource, []string{"list"}, []string{"node_machineset_name.go"}},
	{"hypershift.openshift.io", "nodepools", []string{"list"}, []string{"nodepool_collector.go"}},
	{"hypershift.openshift.io", "hostedclusters", []string{"list"}, []string{"nodepool_collector.go", "hcp_capacity_collector.go"}},
	{"hypershift.openshift.io", "hostedcontrolplanes", []string{"list"}, []string{"hcp_capacity_collector.go"}},
	{snapshotAPIGroup, snapshotResource, []string{"list"}, []string{"snapshot.go"}},
	{instanceTypeAPIGroup, instanceTypeResource, []string{"list"}, []string{"cluster_instance_types.go"}},
	{instanceTypeAPIGroup, preferenceResource, []string{"list"}, []string{"cluster_instance_types.go"}},
	{vmAPIGroup, vmResource, []string{"list"}, []string{"cluster_instance_types.go"}},
	{"", "nodes", []string{"list"}, []string{"hcp_capacity_collector.go"}},
	{"config.openshift.io", "clusterversions", []string{"get"}, []string{"hcp_capacity_collector.go"}},
}

// rbacDocument is the subset of an RBAC manifest these tests need. The
// apimachinery decoder converts YAML to JSON, so the JSON tags apply.
type rbacDocument struct {
	Kind  string     `json:"kind"`
	Rules []rbacRule `json:"rules"`
}

type rbacRule struct {
	APIGroups []string `json:"apiGroups"`
	Resources []string `json:"resources"`
	Verbs     []string `json:"verbs"`
}

func readRBACDocuments(t *testing.T) []rbacDocument {
	t.Helper()

	f, err := os.Open(rbacRoleFile)
	if err != nil {
		t.Fatalf("open %s: %v (run from internal/collector; the file is generated by `make manifests`)", rbacRoleFile, err)
	}
	defer f.Close()

	decoder := yaml.NewYAMLOrJSONDecoder(f, 4096)
	var docs []rbacDocument
	for {
		var doc rbacDocument
		err := decoder.Decode(&doc)
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			t.Fatalf("decode %s: %v", rbacRoleFile, err)
		}
		if doc.Kind == "" {
			continue
		}
		docs = append(docs, doc)
	}
	if len(docs) == 0 {
		t.Fatalf("%s contains no RBAC documents", rbacRoleFile)
	}
	return docs
}

// grantsForKind merges the rules of every document with the given kind into
// group/resource -> verbs.
func grantsForKind(docs []rbacDocument, kind string) map[string][]string {
	grants := make(map[string][]string)
	for _, doc := range docs {
		if doc.Kind != kind {
			continue
		}
		for _, rule := range doc.Rules {
			for _, group := range rule.APIGroups {
				for _, resource := range rule.Resources {
					key := gvrKey(group, resource)
					grants[key] = append(grants[key], rule.Verbs...)
				}
			}
		}
	}
	return grants
}

func gvrKey(group, resource string) string {
	return group + "/" + resource
}

func gvrLabel(group, resource string) string {
	if group == "" {
		return "core/" + resource
	}
	return group + "/" + resource
}

// TestCollectorDynamicReadsAreGranted fails when a dynamic-client read in this
// package has no ClusterRole grant, naming the missing grant and the fix.
func TestCollectorDynamicReadsAreGranted(t *testing.T) {
	docs := readRBACDocuments(t)
	clusterGrants := grantsForKind(docs, "ClusterRole")
	namespacedGrants := grantsForKind(docs, "Role")

	if len(clusterGrants) == 0 {
		t.Fatalf("%s has no ClusterRole rules; cannot verify any cluster-scoped read", rbacRoleFile)
	}

	for _, read := range collectorDynamicReads {
		label := gvrLabel(read.group, read.resource)
		sources := strings.Join(read.sources, ", ")

		granted, ok := clusterGrants[gvrKey(read.group, read.resource)]
		if !ok {
			if _, misplaced := namespacedGrants[gvrKey(read.group, read.resource)]; misplaced {
				t.Errorf("%s reads %s, but it is granted only by the namespaced Role in %s: a cluster-scoped read needs a ClusterRole grant, add +kubebuilder:rbac to internal/controller and run make manifests",
					sources, label, rbacRoleFile)
			} else {
				t.Errorf("%s reads %s (%s) but ClusterRole/manager-role grants none; add +kubebuilder:rbac to internal/controller and run make manifests",
					sources, label, strings.Join(read.verbs, ","))
			}
			continue
		}

		for _, want := range read.verbs {
			if !slices.Contains(granted, want) {
				t.Errorf("%s reads %s with verb %q but ClusterRole/manager-role grants only %v; add +kubebuilder:rbac to internal/controller and run make manifests",
					sources, label, want, granted)
			}
		}
	}
}

// TestCollectorDynamicReadTableIsConsistent keeps the table itself honest: the
// files it names must exist, and no GVR may be pinned twice (a duplicate would
// let one row be updated while the other silently rots).
func TestCollectorDynamicReadTableIsConsistent(t *testing.T) {
	seen := make(map[string]bool, len(collectorDynamicReads))
	for _, read := range collectorDynamicReads {
		key := gvrKey(read.group, read.resource)
		if seen[key] {
			t.Errorf("collectorDynamicReads pins %s twice", gvrLabel(read.group, read.resource))
		}
		seen[key] = true

		if len(read.sources) == 0 {
			t.Errorf("collectorDynamicReads row for %s names no source file", gvrLabel(read.group, read.resource))
		}
		for _, source := range read.sources {
			if _, err := os.Stat(source); err != nil {
				t.Errorf("collectorDynamicReads names %s as a source of %s, but the file does not exist: %v",
					source, gvrLabel(read.group, read.resource), err)
			}
		}
	}
}

// TestCollectorDynamicReadsCoverEveryCollectorFile is the tripwire half: a
// curated table cannot see a GVR added later, so any file that constructs a
// dynamic GroupVersionResource must be named by some row. It catches a new
// collector file; a new read inside an already-listed file still needs the
// review to notice the missing row (see the issue's stated limit).
func TestCollectorDynamicReadsCoverEveryCollectorFile(t *testing.T) {
	tracked := make(map[string]bool)
	for _, read := range collectorDynamicReads {
		for _, source := range read.sources {
			tracked[source] = true
		}
	}

	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("read package directory: %v", err)
	}

	var untracked []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		data, err := os.ReadFile(name)
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		if !bytes.Contains(data, []byte("schema.GroupVersionResource{")) || tracked[name] {
			continue
		}
		untracked = append(untracked, name)
	}

	sort.Strings(untracked)
	if len(untracked) > 0 {
		t.Errorf("these files construct a dynamic GroupVersionResource but no row in collectorDynamicReads names them: %s\n"+
			"add a row for every GVR the file reads, so a missing +kubebuilder:rbac marker fails here instead of in the cluster",
			strings.Join(untracked, ", "))
	}
}
